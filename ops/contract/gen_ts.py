#!/usr/bin/env python3
"""Generate TypeScript wire types from the FastAPI OpenAPI document.

The control plane is the source of truth: routers declare Pydantic response models,
FastAPI publishes them in /openapi.json, and this script turns the component schemas
into a committed TypeScript file. Regenerating must be a no-op in CI, so nothing in
the output depends on clock time, dict insertion order, or local paths.

Usage (from the repo root):

    python ops/contract/gen_ts.py            # write web/src/generated/contract.ts
    python ops/contract/gen_ts.py --check    # fail if the committed file is stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT = REPO_ROOT / "web" / "src" / "generated" / "contract.ts"
HEADER = """// AUTO-GENERATED by ops/contract/gen_ts.py from FastAPI OpenAPI. DO NOT EDIT.
// Source of truth: api/src/l06_api (Pydantic response models).
// Regenerate: python ops/contract/gen_ts.py
"""

_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _page_size_tiers() -> tuple[int, ...]:
    """Backend page-size ladder; exported into TS so the UI cannot drift."""
    src = REPO_ROOT / "api" / "src"
    if str(src) not in sys.path:
        sys.path.insert(0, str(src))
    from l06_api.deps import ALLOWED_PAGE_SIZES

    return tuple(ALLOWED_PAGE_SIZES)


def _openapi_spec() -> dict[str, Any]:
    """Build the app with a throwaway in-memory DB; never touch the dev database."""
    src = REPO_ROOT / "api" / "src"
    if str(src) not in sys.path:
        sys.path.insert(0, str(src))

    from l04_repo.base import init_db
    from l06_api.app import create_app
    from sqlalchemy import create_engine
    from sqlalchemy.orm import sessionmaker
    from sqlalchemy.pool import StaticPool

    engine = create_engine(
        "sqlite://",
        connect_args={"check_same_thread": False},
        poolclass=StaticPool,
        future=True,
    )
    init_db(engine)
    factory = sessionmaker(bind=engine, expire_on_commit=False, autoflush=False, future=True)
    app = create_app(session_factory=factory, init_tables=False)
    return app.openapi()


def _ts_identifier(name: str) -> str:
    return name if _IDENT.match(name) else json.dumps(name, ensure_ascii=False)


def _union(parts: list[str]) -> str:
    seen: list[str] = []
    for part in parts:
        if part not in seen:
            seen.append(part)
    return " | ".join(seen) if seen else "unknown"


def _ts_type(spec: dict[str, Any]) -> str:
    if not spec:
        return "unknown"
    if "$ref" in spec:
        return str(spec["$ref"]).rsplit("/", 1)[-1]
    if "enum" in spec:
        return _union([json.dumps(value, ensure_ascii=False) for value in spec["enum"]])
    if "anyOf" in spec:
        return _union([_ts_type(item) for item in spec["anyOf"]])
    if "oneOf" in spec:
        return _union([_ts_type(item) for item in spec["oneOf"]])
    if "allOf" in spec:
        return " & ".join(_ts_type(item) for item in spec["allOf"])

    kind = spec.get("type")
    if kind == "array":
        item = _ts_type(spec.get("items", {}))
        return f"({item})[]" if " | " in item or " & " in item else f"{item}[]"
    if kind == "object":
        properties = spec.get("properties")
        if not properties:
            return "Record<string, unknown>"
        required = set(spec.get("required", []))
        fields = []
        for name, prop in properties.items():
            key = _ts_identifier(name)
            optional = "" if name in required else "?"
            fields.append(f"{key}{optional}: {_ts_type(prop)};")
        return "{ " + " ".join(fields) + " }"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def _render_enum(name: str, values: list[Any]) -> list[str]:
    lines = [f"export const {name} = {{"]
    for value in values:
        key = _ts_identifier(str(value))
        lines.append(f"  {key}: {json.dumps(value, ensure_ascii=False)},")
    lines.append("} as const;")
    lines.append(f"export type {name} = (typeof {name})[keyof typeof {name}];")
    return lines


def _render_interface(name: str, spec: dict[str, Any]) -> list[str]:
    properties = spec.get("properties", {})
    required = set(spec.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop_name, prop_spec in properties.items():
        key = _ts_identifier(prop_name)
        optional = "" if prop_name in required else "?"
        lines.append(f"  {key}{optional}: {_ts_type(prop_spec)};")
    lines.append("}")
    return lines


def render(spec: dict[str, Any] | None = None) -> str:
    schemas: dict[str, Any] = (spec or _openapi_spec())["components"]["schemas"]
    blocks: list[str] = [HEADER.rstrip()]

    tiers = ", ".join(str(size) for size in _page_size_tiers())
    blocks.append(
        f"export const PAGE_SIZE_TIERS = [{tiers}] as const;\n"
        "export type PageSizeTier = (typeof PAGE_SIZE_TIERS)[number];"
    )

    for name in sorted(schemas):
        schema = schemas[name]
        if not _IDENT.match(name):
            continue
        if "enum" in schema:
            blocks.append("\n".join(_render_enum(name, schema["enum"])))
        elif schema.get("type") == "object" and "properties" in schema:
            blocks.append("\n".join(_render_interface(name, schema)))

    return "\n\n".join(blocks) + "\n"


def write_file(text: str, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="CI: fail when the committed file is stale")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    expected = render()
    output: Path = args.output

    if args.check:
        actual = output.read_text(encoding="utf-8") if output.exists() else ""
        if actual != expected:
            print(
                f"web contract 过期：{output} 与 FastAPI OpenAPI 不一致。\n"
                "请运行 python ops/contract/gen_ts.py 后提交生成结果。",
                file=sys.stderr,
            )
            return 1
        print(f"web contract 已是最新：{output}")
        return 0

    write_file(expected, output)
    print(f"已生成 {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
